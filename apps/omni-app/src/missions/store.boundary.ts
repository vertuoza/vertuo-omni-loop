// The mission store's reads (./store.ts), for `pnpm schemas:verify` (PRD 1030): the mission, its roadmaps and their
// PRDs, the PRDs' stages, pages, approvals, voids and plans, its jobs and their logs (PRD 2871), its events and its fleet's runners, its token budget's caps, stops and pauses (PRD 3040), each parsed
// with the schema the store parses it with. Its send, record and update are not here: they write, and the check only
// reads.
import type { Boundary } from '../boundary.ts';
import {
  ACTOR,
  ActorRowSchema,
  BUG_REPORT,
  BugReportRowSchema,
  REPAIR,
  RepairRowSchema,
  REPOSITORY,
  RepositoryRowSchema,
  APPROVAL,
  ApprovalRowSchema,
  CARE,
  DECISION,
  DecisionRowSchema,
  CareRowSchema,
  DOSSIER,
  DossierRowSchema,
  EVENT,
  EventRowSchema,
  FLEET_EVENT,
  FleetEventRowSchema,
  OVERTURN,
  OverturnRowSchema,
  ASK,
  AskRowSchema,
  JOB,
  JOB_LOG,
  JobLogRowSchema,
  JobRowSchema,
  MISSION,
  PRODUCT,
  ProductRowSchema,
  MissionRowSchema,
  PLAN,
  PlanRowSchema,
  ROADMAP,
  ROADMAP_PRD,
  RoadmapPrdRowSchema,
  RoadmapRowSchema,
  RUNNER,
  RunnerRowSchema,
  RoomRunnerRowSchema,
  RoomJobRowSchema,
  ROOM_RUNNER,
  ROOM_JOB,
  STAGE,
  StageRowSchema,
  VOID,
  WORKSPACE,
  WorkspaceRowSchema,
  VoidRowSchema,
  FLEET_CAP,
  FleetCapRowSchema,
  STOP,
  StopRowSchema,
  PAUSE_EVENT,
  PauseEventRowSchema,
  FLEET_MISSION,
  FleetMissionRowSchema,
} from './store.ts';

export const boundaries: Boundary[] = [
  { name: 'missions/store: missions', read: (db) => db.from('missions').select(MISSION).limit(5), schema: MissionRowSchema, shape: 'rows' },
  { name: 'missions/store: roadmaps', read: (db) => db.from('roadmaps').select(ROADMAP).not('repo', 'is', null).limit(5), schema: RoadmapRowSchema, shape: 'rows' },
  { name: 'missions/store: roadmap PRDs', read: (db) => db.from('roadmap_prds').select(ROADMAP_PRD).limit(5), schema: RoadmapPrdRowSchema, shape: 'rows' },
  { name: 'missions/store: stages', read: (db) => db.from('prd_stages').select(STAGE).limit(5), schema: StageRowSchema, shape: 'rows' },
  { name: 'missions/store: PRD pages', read: (db) => db.from('dossiers').select(DOSSIER).eq('kind', 'prd').not('prd', 'is', null).limit(5), schema: DossierRowSchema, shape: 'rows' },
  { name: 'missions/store: approvals', read: (db) => db.from('approvals').select(APPROVAL).limit(5), schema: ApprovalRowSchema, shape: 'rows' },
  { name: 'missions/store: approval voids', read: (db) => db.from('approval_voids').select(VOID).limit(5), schema: VoidRowSchema, shape: 'rows' },
  { name: 'missions/store: plans', read: (db) => db.from('dossier_versions').select(PLAN).eq('kind', 'plan').limit(1), schema: PlanRowSchema, shape: 'rows' },
  { name: 'missions/store: runner jobs', read: (db) => db.from('runner_jobs').select(JOB).limit(5), schema: JobRowSchema, shape: 'rows' },
  { name: 'missions/store: care jobs', read: (db) => db.from('runner_jobs').select(CARE).not('mission_id', 'is', null).limit(5), schema: CareRowSchema, shape: 'rows' },
  { name: 'missions/store: Reviewer job logs', read: (db) => db.from('runner_jobs').select(JOB_LOG).limit(1), schema: JobLogRowSchema, shape: 'rows' },
  { name: 'missions/store: mission events', read: (db) => db.from('mission_events').select(EVENT).limit(5), schema: EventRowSchema, shape: 'rows' },
  { name: 'missions/store: fleet decisions and overturns', read: (db) => db.from('mission_events').select(FLEET_EVENT).in('kind', ['decided', 'overturned']).limit(5), schema: FleetEventRowSchema, shape: 'rows' },
  { name: 'missions/store: overturned approvals', read: (db) => db.from('mission_events').select(OVERTURN).eq('kind', 'overturned').limit(5), schema: OverturnRowSchema, shape: 'rows' },
  { name: 'missions/store: item committee jobs', read: (db) => db.from('runner_jobs').select(ASK).is('mission_key', null).limit(5), schema: AskRowSchema, shape: 'rows' },
  { name: 'missions/store: committee decisions', read: (db) => db.from('mission_decisions').select(DECISION).limit(5), schema: DecisionRowSchema, shape: 'rows' },
  { name: 'missions/store: products', read: (db) => db.from('products').select(PRODUCT).limit(5), schema: ProductRowSchema, shape: 'rows' },
  { name: 'missions/store: workspaces', read: (db) => db.from('workspaces').select(WORKSPACE).limit(5), schema: WorkspaceRowSchema, shape: 'rows' },
  { name: 'missions/store: runners', read: (db) => db.from('runners').select(RUNNER).limit(5), schema: RunnerRowSchema, shape: 'rows' },
  { name: 'missions/store: room runners', read: (db) => db.from('runners').select(ROOM_RUNNER).limit(5), schema: RoomRunnerRowSchema, shape: 'rows' },
  { name: 'missions/store: mission repairs', read: (db) => db.from('mission_repairs').select(REPAIR).limit(5), schema: RepairRowSchema, shape: 'rows' },
  { name: 'missions/store: Omni Loop bug reports', read: (db) => db.from('omni_bug_reports').select(BUG_REPORT).limit(5), schema: BugReportRowSchema, shape: 'rows' },
  { name: 'missions/store: repositories', read: (db) => db.from('repositories').select(REPOSITORY).limit(5), schema: RepositoryRowSchema, shape: 'rows' },
  { name: 'missions/store: event actors', read: (db) => db.from('mission_events').select(ACTOR).neq('actor', 'agent').limit(5), schema: ActorRowSchema, shape: 'rows' },
  { name: 'missions/store: fleet daily caps', read: (db) => db.from('teams').select(FLEET_CAP).limit(5), schema: FleetCapRowSchema, shape: 'rows' },
  { name: 'missions/store: budget stops', read: (db) => db.from('mission_budget_stops').select(STOP).limit(5), schema: StopRowSchema, shape: 'rows' },
  { name: 'missions/store: pauses and resumes', read: (db) => db.from('mission_events').select(PAUSE_EVENT).in('kind', ['paused', 'resumed']).is('prd', null).limit(5), schema: PauseEventRowSchema, shape: 'rows' },
  { name: 'missions/store: fleet missions', read: (db) => db.from('missions').select(FLEET_MISSION).limit(5), schema: FleetMissionRowSchema, shape: 'rows' },
  { name: 'missions/store: room jobs', read: (db) => db.from('runner_jobs').select(ROOM_JOB).in('status', ['claimed', 'running']).limit(5), schema: RoomJobRowSchema, shape: 'rows' },
];
