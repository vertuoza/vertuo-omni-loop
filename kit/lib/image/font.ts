// The bitmap font of `omni bug film`'s cards (PRD 2100): 6x13 cells in the style of the X11 misc-fixed
// "6x13" face, the one a terminal calls `fixed`, so the cards read like the output they show. ASCII,
// and the marks test runners print (✓ ✗ × ❯ › · • → ─ │). Anything else is the glyph of `?`. The shapes
// are drawn by hand for the kit in that face's cell, not copied from its font file.
//
// Each glyph is written as a picture: `#` is a pixel, `.` is not, rows are separated by a space and
// start at row `top` of the cell. A cell is 13 rows of 6 columns; letters use the first 5 columns, so
// two letters never touch. The baseline sits under row 10: capitals and digits fill rows 2 to 10,
// lowercase rows 4 to 10, and a descender runs on to row 12.

