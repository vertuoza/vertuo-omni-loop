/** A picture's rows as the bitmap of a whole cell: `top` blank rows, the picture, then blank rows. */
function bitmap([top, rows]: readonly [top: number, rows: string]): Glyph {
  const cell: number[] = Array.from({ length: CELL_HEIGHT }, () => 0);
  rows.split(' ').forEach((row, index) => {
    cell[top + index] = Array.from(row).reduce((bits, dot, column) => (dot === '#' ? bits | (1 << (CELL_WIDTH - 1 - column)) : bits), 0);
  });
  return cell;
}

const GLYPHS = new Map<string, Glyph>(Object.entries(PICTURES).map(([character, picture]) => [character, bitmap(picture)]));
const UNKNOWN: Glyph = bitmap(PICTURES['?'] ?? [0, '']);

/** The glyph of one character: its picture, a blank cell for a space, the glyph of `?` for any other. */
export function glyphOf(character: string): Glyph {
  if (character === ' ') return Array.from({ length: CELL_HEIGHT }, () => 0);
  return GLYPHS.get(character) ?? UNKNOWN;
}
