// PRD 1550, s3: the gallery — one HTML page of the whole screen library, generated each time and
// never committed (PRD 1407 keeps no hand-kept index; a committed gallery would be one). Locked
// screens first, then drafts, then superseded, each with its name, its status, who locked it and
// when, its routes, and its mockup inline (or `no mockup`). The page is self-contained: inline CSS,
// no script, no remote asset. Each mockup sits escaped in a sandboxed `srcdoc` frame, so its own CSS
// stays its own, and the page's policy refuses any script or remote asset a mockup might carry.
import type { Library, Screen } from '../screens.ts';

const ORDER: Readonly<Record<Screen['status'], number>> = { locked: 0, draft: 1, superseded: 2 };

/** The screens in gallery order: locked, then drafts, then superseded, the library's order kept within each. */
export function galleryOrder(screens: readonly Screen[]): Screen[] {
  return [...screens].sort((a, b) => ORDER[a.status] - ORDER[b.status]);
}

const escape = (text: string): string =>
  text.replace(/[&<>"']/g, (char) => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' })[char] ?? char);

const POLICY = "default-src 'none'; style-src 'unsafe-inline'; img-src data:";

const STYLE = `
:root { color-scheme: light dark; --ink: #1b1b1f; --muted: #5d5d66; --line: #d9d9de; --paper: #ffffff; --lock: #2f6b3a; }
@media (prefers-color-scheme: dark) { :root { --ink: #ececf1; --muted: #a2a2ad; --line: #3a3a42; --paper: #16161a; --lock: #7fc28a; } }
body { margin: 0; padding: 24px 16px; background: var(--paper); color: var(--ink); font: 15px/1.5 system-ui, sans-serif; }
main { max-width: 1100px; margin: 0 auto; }
h1 { font-size: 22px; margin: 0 0 4px; }
.lede { color: var(--muted); margin: 0 0 24px; }
section { border-top: 1px solid var(--line); padding: 20px 0; }
h2 { font-size: 18px; margin: 0; }
.meta { color: var(--muted); margin: 4px 0 12px; }
.locked .status { color: var(--lock); font-weight: 600; }
iframe { display: block; width: 100%; height: 80vh; min-height: 360px; resize: vertical; overflow: auto; border: 1px solid var(--line); border-radius: 6px; background: #fff; }
.none { color: var(--muted); font-style: italic; }
.problems { color: var(--muted); }
`;

/** One screen's section: its name, status, lock and routes, then its mockup or why there is none. */
function section(screen: Screen, readMock: (mock: string) => string | null): string {
  const lock = screen.lockedBy !== null || screen.lockedOn !== null
    ? ` · locked by ${escape([screen.lockedBy, screen.lockedOn].filter((part) => part !== null).join(' on '))}`
    : '';
  const routes = screen.routes.length ? ` · ${escape(screen.routes.join(', '))}` : '';
  let body = '<p class="none">no mockup</p>';
  if (screen.mock !== null) {
    const html = readMock(screen.mock);
    body = html === null
      ? `<p class="none">mockup cannot be read: ${escape(screen.mock)}</p>`
      : `<iframe sandbox="" title="${escape(screen.screen)}" srcdoc="${escape(html)}"></iframe>`;
  }
  return `<section class="${screen.status}">\n<h2>${escape(screen.screen)}</h2>\n<p class="meta"><span class="status">${screen.status}</span>${lock}${routes}</p>\n${body}\n</section>`;
}

/** The gallery page of `library`; `readMock` gives a mockup's HTML from the screen's `mock` field, or null when it cannot be read. */
export function galleryPage(library: Library, readMock: (mock: string) => string | null): string {
  const screens = galleryOrder(library.screens);
  const problems = library.problems.length
    ? `<section class="problems">\n${library.problems.map((problem) => `<p>does not read: ${escape(problem)}</p>`).join('\n')}\n</section>\n`
    : '';
  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<meta http-equiv="Content-Security-Policy" content="${POLICY}">
<title>Screen gallery</title>
<style>${STYLE}</style>
</head>
<body>
<main>
<h1>Screen gallery</h1>
<p class="lede">${screens.length} screen${screens.length === 1 ? '' : 's'}: locked first, then drafts, then superseded. Generated by omni design gallery; never committed.</p>
${screens.map((screen) => section(screen, readMock)).join('\n')}
${problems}</main>
</body>
</html>
`;
}
