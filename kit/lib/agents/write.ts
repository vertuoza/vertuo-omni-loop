/**
 * **The skills for other agents** (PRD 1890, slice s2). Codex, Cursor and Gemini CLI read a
 * repository's skills from `.agents/skills/<name>/SKILL.md`; this module writes the kit's there, one
 * folder `omni-<name>` per skill, and records what it owns in `.omni-loop/agents.json`.
 *
 * - A copy's `SKILL.md` is the kit's front matter with `name:` rewritten to `omni-<name>` (Cursor
 *   requires the folder's name), then the generated line, then the kit's body byte for byte. Every
 *   other file of the skill is copied under the same relative path, unchanged.
 * - The manifest names each folder the install owns, each file in it with its sha-256, and the kit
 *   version. Nothing outside those folders is ever written or deleted (N-PRODUCT-13, amended): an
 *   `omni-*` folder the manifest does not name is someone else's, and the writer stops on it before
 *   writing anything.
 * - With a non-Claude agent listed, every skill is (re)written, a skill the kit dropped loses its
 *   owned files, and the manifest is rewritten. With `claude` alone, every owned file and the
 *   manifest are removed.
 */
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, readdirSync, readFileSync, rmdirSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join, posix } from 'node:path';
import { z } from 'zod';
import { kitSkills, SKILLS_SOURCE } from './skills.ts';

/** Where the agents read a repository's skills. */
const AGENTS_SKILLS_DIR = '.agents/skills';

/** The manifest of the copies the install owns. */
export const AGENTS_MANIFEST = '.omni-loop/agents.json';

/** The prefix that keeps the kit's skills apart from a repository's own. */
const PREFIX = 'omni-';

/** The agent served by the Claude plugin, not by the copies. */
const CLAUDE = 'claude';

/** A setup the writer refuses: an unowned `omni-*` folder, a manifest it cannot trust, a skill with
 * no `name:`. Its message is one line naming the path. */
export class AgentsError extends Error {
  override name = 'AgentsError';
}

/** An owned folder, `.agents/skills/omni-<name>`, with no `..` and no deeper path. */
const OWNED_FOLDER = /^\.agents\/skills\/omni-[A-Za-z0-9][A-Za-z0-9._-]*$/;

const ManifestSchema = z.strictObject({
  version: z.string().nullable(),
  folders: z.record(z.string(), z.record(z.string(), z.string())),
});

/** `.omni-loop/agents.json`: `{ version, folders: { <folder>: { <file>: <sha-256> } } }`, every path
 * posix and from the repository root. */
export type AgentsManifest = z.infer<typeof ManifestSchema>;

/** One owned folder whose copy moved: `lines` counts the lines changed, the generated line aside. */
export type AgentCopyChange =
  | { folder: string; change: 'new' }
  | { folder: string; change: 'changed'; lines: number }
  | { folder: string; change: 'removed' };

const sha256 = (text: string): string => createHash('sha256').update(text, 'utf8').digest('hex');

/** The generated line of a copy of skill `name`, built by kit `version`. */
function generatedLine(name: string, version: string | null): string {
  return `<!-- generated by omni ${version ?? '(unversioned)'} from ${SKILLS_SOURCE}/${name}; omni update rewrites it -->`;
}

const GENERATED_PREFIX = '<!-- generated by omni ';

/**
 * The copy of skill `name`'s `SKILL.md` (`text`): its front matter with `name:` rewritten to
 * `omni-<name>`, the generated line, then the body after the front matter, byte for byte.
 */
export function skillCopy(name: string, text: string, version: string | null): string {
  const fence = /^---\n([\s\S]*?\n)---\n/.exec(text);
  const front = fence?.[1];
  if (fence === null || front === undefined || !/^name:.*$/m.test(front)) {
    throw new AgentsError(`${SKILLS_SOURCE}/${name}/SKILL.md has no front matter with a name: line`);
  }
  const renamed = front.replace(/^name:.*$/m, `name: ${PREFIX}${name}`);
  return `---\n${renamed}---\n${generatedLine(name, version)}\n${text.slice(fence[0].length)}`;
}

/** Every file the copies hold, `{ <folder>: { <file>: text } }`, from the kit's `skills`. */
function copiesOf(skills: Record<string, string>, version: string | null): Map<string, Map<string, string>> {
  const out = new Map<string, Map<string, string>>();
  for (const [path, text] of Object.entries(skills)) {
    const slash = path.indexOf('/');
    if (slash <= 0) continue;
    const name = path.slice(0, slash);
    const rest = path.slice(slash + 1);
    const folder = `${AGENTS_SKILLS_DIR}/${PREFIX}${name}`;
    const files = out.get(folder) ?? new Map<string, string>();
    files.set(`${folder}/${rest}`, rest === 'SKILL.md' ? skillCopy(name, text, version) : text);
    out.set(folder, files);
  }
  return out;
}

/** Whether `file` lies inside owned `folder`, by its plain path. */
function insideFolder(folder: string, file: string): boolean {
  return file.startsWith(`${folder}/`) && posix.normalize(file) === file && !file.split('/').includes('..');
}

/** The manifest of `root`, or `null` when there is none. A manifest that is no JSON, or names a
 * path outside `.agents/skills/omni-*`, is refused: the writer never acts on it. */
export function readManifest(root: string): AgentsManifest | null {
  const file = join(root, AGENTS_MANIFEST);
  if (!existsSync(file)) return null;
  let parsed: AgentsManifest;
  try {
    parsed = ManifestSchema.parse(JSON.parse(readFileSync(file, 'utf8')));
  } catch {
    throw new AgentsError(`${AGENTS_MANIFEST} is not the manifest omni writes; restore it from git, then run again`);
  }
  for (const [folder, files] of Object.entries(parsed.folders)) {
    const stray = OWNED_FOLDER.test(folder) ? Object.keys(files).find((path) => !insideFolder(folder, path)) : folder;
    if (stray !== undefined) throw new AgentsError(`${AGENTS_MANIFEST} names ${stray}, outside ${AGENTS_SKILLS_DIR}/${PREFIX}*; restore it from git, then run again`);
  }
  return parsed;
}

/** The `omni-*` entries of `.agents/skills/` the manifest does not own. */
function unowned(root: string, manifest: AgentsManifest | null): string[] {
  const dir = join(root, AGENTS_SKILLS_DIR);
  if (!existsSync(dir)) return [];
  return readdirSync(dir)
    .filter((name) => name.startsWith(PREFIX))
    .map((name) => `${AGENTS_SKILLS_DIR}/${name}`)
    .filter((folder) => !manifest || !Object.hasOwn(manifest.folders, folder))
    .sort();
}

/** The text of a repository file, or `null` when it is missing. */
function textOf(root: string, path: string): string | null {
  const file = join(root, path);
  return existsSync(file) ? readFileSync(file, 'utf8') : null;
}

/** The lines of a copy's files, the generated line aside, as a count per line. */
function lineCounts(texts: Iterable<string>): Map<string, number> {
  const counts = new Map<string, number>();
  for (const text of texts) {
    for (const line of text.split('\n')) {
      if (line.startsWith(GENERATED_PREFIX)) continue;
      counts.set(line, (counts.get(line) ?? 0) + 1);
    }
  }
  return counts;
}

/** How many lines changed between two copies of a folder: the larger of the lines gone and come. */
function linesChanged(before: Iterable<string>, after: Iterable<string>): number {
  const was = lineCounts(before);
  const now = lineCounts(after);
  let gone = 0;
  let come = 0;
  for (const [line, n] of was) gone += Math.max(0, n - (now.get(line) ?? 0));
  for (const [line, n] of now) come += Math.max(0, n - (was.get(line) ?? 0));
  return Math.max(gone, come);
}

/** Removes `path`'s parent folders up to `stop`, each only while it is empty. */
function pruneEmpty(root: string, path: string, stop: string): void {
  let dir = dirname(path);
  while (dir.startsWith(`${stop}/`) || dir === stop) {
    const abs = join(root, dir);
    if (!existsSync(abs) || readdirSync(abs).length > 0) return;
    rmdirSync(abs);
    if (dir === stop) return;
    dir = dirname(dir);
  }
}

/** Deletes the owned `files` of `folder`, then the folders they leave empty. A person's own file in
 * the folder stays. */
function removeOwned(root: string, folder: string, files: Iterable<string>): void {
  for (const path of files) {
    rmSync(join(root, path), { force: true });
    pruneEmpty(root, path, folder);
  }
}

/** Stops on any `omni-*` entry of `.agents/skills/` the manifest does not own, naming each. */
function refuseForeign(root: string, manifest: AgentsManifest | null): void {
  const foreign = unowned(root, manifest);
  if (foreign.length === 0) return;
  const one = foreign.length === 1;
  throw new AgentsError(`${foreign.join(', ')} ${one ? 'is' : 'are'} not omni's (not in ${AGENTS_MANIFEST}): move or rename ${one ? 'it' : 'them'}, then run again`);
}

/** Writes `files` into owned `folder`, dropping the owned files (`had`) the new copy lacks. Returns
 * the files' hashes and the folder's change, `null` when only the generated line moved. */
function writeFolder(root: string, folder: string, files: Map<string, string>, had: Record<string, string> | undefined): { record: Record<string, string>; change: AgentCopyChange | null } {
  const was = Object.keys(had ?? {});
  const before = was.map((path) => textOf(root, path) ?? '');
  removeOwned(root, folder, was.filter((path) => !files.has(path)));
  const record: Record<string, string> = {};
  for (const [path, text] of [...files].sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))) {
    mkdirSync(dirname(join(root, path)), { recursive: true });
    writeFileSync(join(root, path), text);
    record[path] = sha256(text);
  }
  if (!had) return { record, change: { folder, change: 'new' } };
  const lines = linesChanged(before, files.values());
  const sameFiles = was.length === files.size && was.every((path) => files.has(path));
  return { record, change: lines > 0 || !sameFiles ? { folder, change: 'changed', lines } : null };
}

/**
 * Brings `.agents/skills/omni-*` and the manifest in line with `agents` and the kit's `skills`
 * (the running kit's by default), built by kit `version`. Returns the owned folders whose copy moved,
 * in path order; a version alone moves none. Throws {@link AgentsError}, before writing anything, on
 * an `omni-*` folder the manifest does not own or a manifest it cannot trust.
 */
export function syncAgentSkills({
  root,
  agents,
  version,
  skills = kitSkills(),
}: {
  root: string;
  agents: readonly string[];
  version: string | null;
  skills?: Record<string, string>;
}): { changes: AgentCopyChange[] } {
  const manifest = readManifest(root);
  const owned = manifest?.folders ?? {};
  const wanted = agents.some((agent) => agent !== CLAUDE) ? copiesOf(skills, version) : new Map<string, Map<string, string>>();
  if (wanted.size > 0) refuseForeign(root, manifest);

  const changes: AgentCopyChange[] = [];
  const next: AgentsManifest = { version, folders: {} };
  for (const folder of [...new Set([...Object.keys(owned), ...wanted.keys()])].sort()) {
    const had = owned[folder];
    const files = wanted.get(folder);
    if (files) {
      const { record, change } = writeFolder(root, folder, files, had);
      next.folders[folder] = record;
      if (change) changes.push(change);
    } else if (had) {
      removeOwned(root, folder, Object.keys(had));
      changes.push({ folder, change: 'removed' });
    }
  }

  const manifestFile = join(root, AGENTS_MANIFEST);
  if (wanted.size > 0) {
    mkdirSync(dirname(manifestFile), { recursive: true });
    writeFileSync(manifestFile, `${JSON.stringify(next, null, 2)}\n`);
  } else if (manifest) {
    rmSync(manifestFile, { force: true });
  }
  return { changes };
}
