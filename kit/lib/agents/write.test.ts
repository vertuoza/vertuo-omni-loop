// PRD 1890, slice s2: the writer of `.agents/skills/omni-<name>/`, the copies Codex, Cursor and
// Gemini CLI read, and the manifest that says which of them the install owns (N-PRODUCT-13, amended).
import { createHash } from 'node:crypto';
import { existsSync, mkdirSync, mkdtempSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { describe, expect, it } from 'vitest';
import { kitSkills } from './skills.ts';
import { AGENTS_MANIFEST, AgentsError, readManifest, skillCopy, syncAgentSkills } from './write.ts';

const sha256 = (text: string) => createHash('sha256').update(text, 'utf8').digest('hex');

/** A small set of skills, as the bundle carries them. */
const SKILLS: Record<string, string> = {
  'yolo/SKILL.md': '---\nname: yolo\ndescription: Build a whole PRD.\n---\n\n# Yolo\n\nRun /omni:wave.\n',
  'pixel-perfect/SKILL.md': '---\nname: pixel-perfect\ndescription: Screens.\n---\n\nRead [the mock](mock.md) and [review](reference/review.md).\n',
  'pixel-perfect/mock.md': '# Mock\n',
  'pixel-perfect/reference/review.md': '# Review\n',
};

function tempRepo(files: Record<string, string> = {}): string {
  const root = mkdtempSync(join(tmpdir(), 'omni-agents-'));
  for (const [path, text] of Object.entries(files)) {
    mkdirSync(dirname(join(root, path)), { recursive: true });
    writeFileSync(join(root, path), text);
  }
  return root;
}

const read = (root: string, path: string) => readFileSync(join(root, path), 'utf8');

/** Every file under `dir` of `root`, as posix paths from `root`. */
function filesUnder(root: string, dir: string): string[] {
  if (!existsSync(join(root, dir))) return [];
  return readdirSync(join(root, dir), { recursive: true, withFileTypes: true })
    .filter((entry) => entry.isFile())
    .map((entry) => join(entry.parentPath, entry.name).slice(root.length + 1).split('\\').join('/'))
    .sort();
}

describe('skillCopy', () => {
  it('rewrites name: to omni-<name>, adds the generated line, keeps the body byte-identical', () => {
    const text = SKILLS['yolo/SKILL.md'] ?? '';
    const copy = skillCopy('yolo', text, '0.0.404');
    const lines = copy.split('\n');
    expect(lines.slice(0, 5)).toEqual([
      '---',
      'name: omni-yolo',
      'description: Build a whole PRD.',
      '---',
      '<!-- generated by omni 0.0.404 from kit/plugin/skills/yolo; omni update rewrites it -->',
    ]);
    const body = text.slice(text.indexOf('\n---\n') + 5);
    expect(copy.endsWith(body)).toBe(true);
    expect(copy.slice(copy.indexOf('-->\n') + 4)).toBe(body);
  });

  it('names an unversioned kit as such', () => {
    expect(skillCopy('yolo', SKILLS['yolo/SKILL.md'] ?? '', null)).toContain('<!-- generated by omni (unversioned) from kit/plugin/skills/yolo;');
  });

  it('refuses a skill with no front matter or no name:', () => {
    expect(() => skillCopy('x', '# no front matter\n', '1.0.0')).toThrow(AgentsError);
    expect(() => skillCopy('x', '---\ndescription: d\n---\nbody\n', '1.0.0')).toThrow(/x\/SKILL\.md/);
  });

  it('holds for every skill the kit carries: name: equals the folder, the body after the generated line is the kit\u2019s', () => {
    const skills = kitSkills();
    const names = Object.keys(skills).filter((p) => p.endsWith('/SKILL.md')).map((p) => p.slice(0, -'/SKILL.md'.length));
    expect(names.length).toBeGreaterThan(20);
    for (const name of names) {
      const text = skills[`${name}/SKILL.md`] ?? '';
      const copy = skillCopy(name, text, '1.2.3');
      expect(/^---\n[\s\S]*?^name: (.*)$/m.exec(copy)?.[1], name).toBe(`omni-${name}`);
      expect(copy.slice(copy.indexOf('-->\n') + 4), name).toBe(text.slice(text.indexOf('\n---\n') + 5));
    }
  });
});

describe('syncAgentSkills', () => {
  it('for [codex], writes one omni-<name> folder per skill, the siblings under the same paths, and the manifest', () => {
    const root = tempRepo();
    const result = syncAgentSkills({ root, agents: ['codex'], version: '0.0.404', skills: SKILLS });

    expect(filesUnder(root, '.agents')).toEqual([
      '.agents/skills/omni-pixel-perfect/SKILL.md',
      '.agents/skills/omni-pixel-perfect/mock.md',
      '.agents/skills/omni-pixel-perfect/reference/review.md',
      '.agents/skills/omni-yolo/SKILL.md',
    ]);
    expect(read(root, '.agents/skills/omni-yolo/SKILL.md')).toBe(skillCopy('yolo', SKILLS['yolo/SKILL.md'] ?? '', '0.0.404'));
    expect(read(root, '.agents/skills/omni-pixel-perfect/mock.md')).toBe(SKILLS['pixel-perfect/mock.md']);
    expect(read(root, '.agents/skills/omni-pixel-perfect/reference/review.md')).toBe(SKILLS['pixel-perfect/reference/review.md']);

    const manifest = readManifest(root);
    expect(manifest?.version).toBe('0.0.404');
    expect(Object.keys(manifest?.folders ?? {}).sort()).toEqual(['.agents/skills/omni-pixel-perfect', '.agents/skills/omni-yolo']);
    for (const path of filesUnder(root, '.agents')) {
      const folder = path.split('/').slice(0, 3).join('/');
      expect(manifest?.folders[folder]?.[path], path).toBe(sha256(read(root, path)));
    }
    expect(result.changes).toEqual([
      { folder: '.agents/skills/omni-pixel-perfect', change: 'new' },
      { folder: '.agents/skills/omni-yolo', change: 'new' },
    ]);
  });

  it('for [claude] alone, on a repository never installed, writes nothing', () => {
    const root = tempRepo();
    const result = syncAgentSkills({ root, agents: ['claude'], version: '0.0.404', skills: SKILLS });
    expect(existsSync(join(root, '.agents'))).toBe(false);
    expect(existsSync(join(root, AGENTS_MANIFEST))).toBe(false);
    expect(result.changes).toEqual([]);
  });

  it('leaves a foreign skill byte-identical', () => {
    const foreign = { '.agents/skills/my-skill/SKILL.md': '---\nname: my-skill\n---\nmine\n', '.agents/skills/README.md': 'ours\n' };
    const root = tempRepo(foreign);
    syncAgentSkills({ root, agents: ['cursor', 'gemini'], version: '1.0.0', skills: SKILLS });
    syncAgentSkills({ root, agents: ['claude'], version: '1.0.0', skills: SKILLS });
    for (const [path, text] of Object.entries(foreign)) expect(read(root, path)).toBe(text);
  });

});

describe('syncAgentSkills, around what is not omni’s', () => {
  it('stops before any write on an omni-* folder the manifest does not own, naming it', () => {
    const root = tempRepo({ '.agents/skills/omni-x/SKILL.md': 'someone else\n' });
    expect(() => syncAgentSkills({ root, agents: ['codex'], version: '1.0.0', skills: SKILLS })).toThrow(AgentsError);
    expect(() => syncAgentSkills({ root, agents: ['codex'], version: '1.0.0', skills: SKILLS })).toThrow(/\.agents\/skills\/omni-x/);
    expect(filesUnder(root, '.agents')).toEqual(['.agents/skills/omni-x/SKILL.md']);
    expect(existsSync(join(root, AGENTS_MANIFEST))).toBe(false);
  });

  it('stops on an unowned omni-* folder even once a manifest exists', () => {
    const root = tempRepo();
    syncAgentSkills({ root, agents: ['codex'], version: '1.0.0', skills: SKILLS });
    const manifest = read(root, AGENTS_MANIFEST);
    mkdirSync(join(root, '.agents/skills/omni-x'));
    writeFileSync(join(root, '.agents/skills/omni-x/SKILL.md'), 'mine\n');
    expect(() => syncAgentSkills({ root, agents: ['codex'], version: '2.0.0', skills: SKILLS })).toThrow(/omni-x/);
    expect(read(root, AGENTS_MANIFEST)).toBe(manifest);
  });

});

describe('syncAgentSkills, on a rerun', () => {
  it('on a rerun, rewrites a changed skill, adds a new one, and removes only the owned folder of a dropped one', () => {
    const root = tempRepo({ '.agents/skills/my-skill/SKILL.md': 'mine\n' });
    syncAgentSkills({ root, agents: ['codex'], version: '1.0.0', skills: SKILLS });
    const next: Record<string, string> = {
      'yolo/SKILL.md': '---\nname: yolo\ndescription: Build a whole PRD.\n---\n\n# Yolo\n\nRun /omni:wave, then ship.\n',
      'think-big/SKILL.md': '---\nname: think-big\ndescription: Big.\n---\nbody\n',
    };
    const result = syncAgentSkills({ root, agents: ['codex'], version: '2.0.0', skills: next });

    expect(filesUnder(root, '.agents')).toEqual([
      '.agents/skills/my-skill/SKILL.md',
      '.agents/skills/omni-think-big/SKILL.md',
      '.agents/skills/omni-yolo/SKILL.md',
    ]);
    expect(read(root, '.agents/skills/omni-yolo/SKILL.md')).toContain('Run /omni:wave, then ship.');
    expect(Object.keys(readManifest(root)?.folders ?? {}).sort()).toEqual(['.agents/skills/omni-think-big', '.agents/skills/omni-yolo']);
    expect(result.changes).toEqual([
      { folder: '.agents/skills/omni-pixel-perfect', change: 'removed' },
      { folder: '.agents/skills/omni-think-big', change: 'new' },
      { folder: '.agents/skills/omni-yolo', change: 'changed', lines: 1 },
    ]);
  });

  it('reports no change when nothing moved but the version, and still stamps the new version', () => {
    const root = tempRepo();
    syncAgentSkills({ root, agents: ['codex'], version: '1.0.0', skills: SKILLS });
    expect(syncAgentSkills({ root, agents: ['codex'], version: '1.0.1', skills: SKILLS }).changes).toEqual([]);
    expect(read(root, '.agents/skills/omni-yolo/SKILL.md')).toContain('generated by omni 1.0.1 ');
    expect(readManifest(root)?.version).toBe('1.0.1');
  });

  it('keeps a file a person added inside an owned folder when the folder is dropped', () => {
    const root = tempRepo();
    syncAgentSkills({ root, agents: ['codex'], version: '1.0.0', skills: SKILLS });
    writeFileSync(join(root, '.agents/skills/omni-yolo/notes.md'), 'mine\n');
    syncAgentSkills({ root, agents: ['codex'], version: '2.0.0', skills: { 'pixel-perfect/SKILL.md': SKILLS['pixel-perfect/SKILL.md'] ?? '' } });
    expect(filesUnder(root, '.agents/skills/omni-yolo')).toEqual(['.agents/skills/omni-yolo/notes.md']);
    expect(filesUnder(root, '.agents/skills/omni-pixel-perfect')).toEqual(['.agents/skills/omni-pixel-perfect/SKILL.md']);
  });

  it('with agents back to [claude], removes every owned folder and the manifest, and nothing else', () => {
    const root = tempRepo({ '.agents/skills/my-skill/SKILL.md': 'mine\n' });
    syncAgentSkills({ root, agents: ['claude', 'codex'], version: '1.0.0', skills: SKILLS });
    const result = syncAgentSkills({ root, agents: ['claude'], version: '1.0.0', skills: SKILLS });
    expect(filesUnder(root, '.agents')).toEqual(['.agents/skills/my-skill/SKILL.md']);
    expect(existsSync(join(root, AGENTS_MANIFEST))).toBe(false);
    expect(result.changes).toEqual([
      { folder: '.agents/skills/omni-pixel-perfect', change: 'removed' },
      { folder: '.agents/skills/omni-yolo', change: 'removed' },
    ]);
  });

  it('refuses a manifest that names a path outside .agents/skills/omni-*, writing and deleting nothing', () => {
    const root = tempRepo({
      'keep.txt': 'keep\n',
      [AGENTS_MANIFEST]: JSON.stringify({ version: '1.0.0', folders: { '.agents/skills/omni-yolo': { 'keep.txt': sha256('keep\n') } } }),
    });
    expect(() => syncAgentSkills({ root, agents: ['claude'], version: '1.0.0', skills: SKILLS })).toThrow(AgentsError);
    expect(read(root, 'keep.txt')).toBe('keep\n');
    const escaping = tempRepo({ [AGENTS_MANIFEST]: JSON.stringify({ version: '1.0.0', folders: { '.agents/skills/omni-yolo/../..': {} } }) });
    expect(() => readManifest(escaping)).toThrow(AgentsError);
    const broken = tempRepo({ [AGENTS_MANIFEST]: '{ not json' });
    expect(() => readManifest(broken)).toThrow(/agents\.json/);
  });
});
