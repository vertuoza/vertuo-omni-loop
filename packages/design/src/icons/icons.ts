/** The name of an icon of the set. */
export type IconName = keyof typeof GLYPHS;

/** Every icon's name: the app's navigation and the controls around it. */
export const ICON_NAMES: readonly IconName[] = Object.freeze(Object.keys(GLYPHS).filter((name): name is IconName => name in GLYPHS));

/** An icon's grid: 16 rows of 16 characters, `#` for an on pixel and `.` for an off one. */
export const ICON_GRIDS: Readonly<Record<IconName, readonly string[]>> = GLYPHS;

/** An icon drawn as an SVG string: one rect per on pixel run, filled `currentColor`, crisp at a whole-number `scale`. */
export function drawIcon(name: IconName, scale = 1): string {
  if (!Number.isInteger(scale) || scale < 1) throw new Error(`icon scale must be a whole number of at least 1, got ${String(scale)}`);
  const size = ICON_SIZE * scale;
  const path = ICON_GRIDS[name]
    .flatMap((row, y) => [...row.matchAll(/#+/g)].map((run) => `M${String(run.index)} ${String(y)}h${String(run[0].length)}v1h-${String(run[0].length)}z`))
    .join('');
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${String(size)}" height="${String(size)}" viewBox="0 0 ${String(ICON_SIZE)} ${String(ICON_SIZE)}" shape-rendering="crispEdges" fill="currentColor" role="img" aria-label="${name}"><path d="${path}"/></svg>`;
}
